const img = (folder: string, file: string) => `/images/products/${folder}/${file}.jpeg`

/** [slug del color, archivo de foto (opcional)] */
function colors(folder: string, list: [string, string?][]): Color[] {
  return list.map(([slug, file]) => ({
    slug,
    name: C[slug]?.name ?? slug,
    hex: C[slug]?.hex ?? "#cccccc",
    image: file ? img(folder, file) : undefined,
  }))
}

const tiers = (t3: number, t5?: number): PriceTier[] =>
  t5 ? [{ minQty: 3, unitPrice: t3 }, { minQty: 5, unitPrice: t5 }] : [{ minQty: 3, unitPrice: t3 }]

